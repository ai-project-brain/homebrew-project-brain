  def install
    # The Python package source lives at mcp/ inside the repo tarball.
    # `virtualenv_install_with_resources` assumes the package is at the
    # build-path root, which it isn't. Drop down to the lower-level helpers
    # so we can point pip at `buildpath/"mcp"` explicitly for the final
    # install-and-link step.
    venv = virtualenv_create(libexec, "python3.13")
    venv.pip_install resources
    venv.pip_install_and_link buildpath/"mcp"
  end

  service do
    run [opt_bin/"project-brain-mcp", "--http"]
    keep_alive true
    log_path var/"log/project-brain-mcp.log"
    error_log_path var/"log/project-brain-mcp.error.log"
  end

  test do
    # Liveness check: the binary speaks MCP over stdio. With stdin closed
    # the server exits cleanly. A full client handshake would require the
    # mcp SDK in the test environment; we keep this lightweight.
    assert_path_exists bin/"project-brain-mcp"
    system "perl", "-e", "alarm 5; exec 'project-brain-mcp' or die"
  end
